#!/usr/bin/env node
// Universal Screens' own icon (James, 2026-11-05, proposal "H — one picture,
// split"): a desk screen and a phone on a teal ground, with ONE orange disc
// drawn across both of them. The disc is a single circle clipped to the two
// glass faces, so the arc leaving the monitor and the arc arriving on the
// phone are the same curve — that is the whole idea, and it is why the two
// devices sit apart with a gap rather than overlapping. Drawn once, below;
// every installed-app icon file is rendered from it.
//
//   node scripts/app-icon.mjs
//   PLAYWRIGHT=/some/other/playwright/index.mjs node scripts/app-icon.mjs
//
// This repo has no package.json, so there is no local playwright to resolve.
// The default is the suite's copy under backoffice/universal-platform, the
// same one the app-mark generators use; PLAYWRIGHT overrides it.
//
// ── What is ours and what stays the suite's ──────────────────────────────────
//
// Screens' INSTALLED apps are its own now, not the suite mark on the orange
// tile, so the suite generators skip them (`ownNativeIcon` and
// `ownDesktopIcon` in backoffice/universal-platform/scripts/app-marks/
// marks.mjs). Following Universal PDF's precedent exactly, two things stay
// the suite's and are NOT written here:
//
//   • the installer icon (crates/host-windows/assets/installer-icon.ico, the
//     orange tile with the globe seal): an installer is not the app
//   • the IN-APP product logo — apps/android/.../drawable/app_icon.png and
//     apps/ios/.../AppLogo.imageset/logo.png. Those are the phone client's
//     masthead mark, the equivalent of PDF's ProductLogo in a navbar, and the
//     suite mark is what belongs in a suite chrome. desktop-icons.mjs still
//     writes both.
//
// The WEB surfaces are this icon too, not the orange mark: James, 2026-11-03,
// "where an application has been published on any device other than web use
// the new logo everywhere (including favicon); keep the orange logos
// specifically for web based apps to easily tell them apart". Screens ships a
// desktop app and two phone clients, so it qualifies. That side is the suite
// generator's job via `webIcon` + SVG_OUT below, not this script's.
//
// What it writes:
//   Windows  crates/host-windows/assets/app-icon.png (256) — the window and
//            taskbar icon, and the badge in the middle of the host's QR codes
//            (see crates/host-windows/src/qr.rs) — and app-icon.ico, which
//            build.rs stamps into the .exe and the installer uses for every
//            shortcut and the Add/Remove Programs entry
//   macOS    crates/host-macos/assets/app-icon.png (1024, window + QR badge)
//            and AppIcon.icns, the Dock icon, inset on Apple's 824/1024 grid
//   Linux    crates/host-linux/assets/app-icon.png (512) — window, QR badge,
//            and the AppImage's own icon (scripts/build-appimage.sh copies it)
//   Android  mipmap-*/ic_launcher.png + ic_launcher_round.png (pre-Android 8),
//            mipmap-*/ic_launcher_foreground.png and the teal background the
//            adaptive icon composites it over
//   iOS      AppIcon.appiconset/icon-1024.png, opaque
//
// ⚠️ No lettering, nothing thinner than ~40/1024. Every file here is also
// rendered at 32px or smaller somewhere.
//
// ⚠️ THESE FILES ARE COMMITTED AND MUST NOT BE REGENERATED BY A BUILD. The
// four scripts/make-*.py icon scripts draw the pre-rebrand laptop-and-phone
// artwork and are superseded; build-installer.ps1 and macos-release.yml used
// to run them and silently reverted the icon on every build (v0.4.3's DMG
// shipped the old mark because of it). Run this script deliberately, look at
// what it writes, and commit it.
//
// ⚠️ ADAPTIVE LAYERS ARE 108dp AND A LAUNCHER SHOWS ONLY THE MIDDLE ~72dp.
// The layers draw the art with the viewBox widened (1660 for 1024, as PDF's),
// so what a launcher shows matches the iOS icon rather than a shrunken copy
// floating inside the mask.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PLAYWRIGHT = process.env.PLAYWRIGHT
  ?? path.resolve(root, '../../backoffice/universal-platform/node_modules/playwright/index.mjs')
const { chromium } = await import(pathToFileURL(PLAYWRIGHT).href)

// ── Palette ─────────────────────────────────────────────────────────────────
// Teal, not the suite's orange: the tile is the ground here, and an orange
// ground would leave nowhere for the orange accent to read. Teal is also the
// one ground of the four proposed that no other UNI·SIM app uses — PDF is
// cobalt, and two apps sharing a ground defeats the point of each having one.
const TEAL = '#1a7a80'
const TEAL_DEEP = '#063b44'
/** The suite's orange, exactly as the canonical tile mixes it. */
const ORANGE = '#fe8c01'
const ORANGE_DEEP = '#e05504'
/** The lit glass. */
const CREAM = '#f4f1ea'
/** The bezel, stand and phone shell: cream a shade down, so edges read. */
const EDGE = '#d9d2c2'
/** The home bar. */
const GREY = '#b7bfcd'

// ── The drawing, on a 1024 grid ─────────────────────────────────────────────
// Monitor 70..620 × 196..666 with its stand to 766; phone 688..952 × 330..814.
// ⚠️ The 68px gap between them is load-bearing and was 48 in the first cut.
// It is what the disc jumps, so it has to survive the small sizes: 48/1024 is
// 1.5px at 32 and vanishes at 16, which turned the pair into one blob. 68 is
// the widest gap that still leaves the monitor reading as the larger screen.
const MONITOR = { x: 70, y: 196, w: 550, h: 470, r: 40 }
const MON_FACE = { x: 92, y: 218, w: 506, h: 426, r: 22 }
const PHONE = { x: 688, y: 330, w: 264, h: 484, r: 58 }
const PH_FACE = { x: 708, y: 350, w: 224, h: 444, r: 40 }
// ⚠️ r=300, not 290. At 290 the circle's right edge lands at x=930 and the
// phone's glass runs to 932, leaving a two-pixel cream sliver down the right
// edge that looks like a rendering fault rather than a choice. Visible only in
// the render, never in the numbers.
const DISC = { cx: 636, cy: 470, r: 300 }
/** The stand, centred under the monitor. */
const NECK = { x: 277, y: 666, w: 136, h: 56 }
const BASE = { x: 191, y: 718, w: 308, h: 48, r: 24 }

const rect = (o, fill) =>
  `<rect x="${o.x}" y="${o.y}" width="${o.w}" height="${o.h}" rx="${o.r ?? 0}" fill="${fill}"/>`

/**
 * The icon as SVG on a 1024 grid.
 * @param {{ wide?: boolean, back?: boolean, front?: boolean }} o
 *   wide — the 108dp adaptive canvas (viewBox widened, see the header);
 *   back / front — which layers to draw (both by default).
 */
function svg({ wide = false, back = true, front = true } = {}) {
  const box = wide ? '-318 -318 1660 1660' : '0 0 1024 1024'
  const ground = `<rect x="-340" y="-340" width="1704" height="1704" fill="url(#bg)"/>`
  const art = `
    <g transform="translate(14 22)" fill="rgba(0,0,0,0.26)">
      ${rect(MONITOR, 'rgba(0,0,0,0.26)')}
      ${rect(NECK, 'rgba(0,0,0,0.26)')}
      ${rect(BASE, 'rgba(0,0,0,0.26)')}
      ${rect(PHONE, 'rgba(0,0,0,0.26)')}
    </g>
    ${rect(MONITOR, EDGE)}
    ${rect(MON_FACE, 'url(#cream)')}
    ${rect(NECK, EDGE)}
    ${rect(BASE, EDGE)}
    ${rect(PHONE, EDGE)}
    ${rect(PH_FACE, 'url(#cream)')}
    <rect x="782" y="768" width="76" height="14" rx="7" fill="${GREY}"/>
    <g clip-path="url(#faces)">
      <circle cx="${DISC.cx}" cy="${DISC.cy}" r="${DISC.r}" fill="url(#orange)"/>
      <circle cx="${DISC.cx}" cy="${DISC.cy}" r="${DISC.r}" fill="none"
              stroke="${ORANGE_DEEP}" stroke-width="18" opacity="0.35"/>
    </g>`
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box}" width="100%" height="100%">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${TEAL}"/><stop offset="1" stop-color="${TEAL_DEEP}"/></linearGradient>
    <linearGradient id="cream" x1="0" y1="0" x2="0.4" y2="1"><stop offset="0" stop-color="#fbf9f4"/><stop offset="1" stop-color="${CREAM}"/></linearGradient>
    <linearGradient id="orange" x1="0" y1="0" x2="0.3" y2="1"><stop offset="0" stop-color="${ORANGE}"/><stop offset="1" stop-color="${ORANGE_DEEP}"/></linearGradient>
    <clipPath id="faces">
      <rect x="${MON_FACE.x}" y="${MON_FACE.y}" width="${MON_FACE.w}" height="${MON_FACE.h}" rx="${MON_FACE.r}"/>
      <rect x="${PH_FACE.x}" y="${PH_FACE.y}" width="${PH_FACE.w}" height="${PH_FACE.h}" rx="${PH_FACE.r}"/>
    </clipPath>
  </defs>
  ${back ? ground : ''}
  ${front ? art : ''}
</svg>`
}

// SVG_OUT=<file>: write the icon as one SVG (the 1024 square, every layer) and
// stop. The suite's marks generator puts that file on every web surface once
// the app is published beyond the web (James, 2026-11-03): the favicon, the
// header logo, the app switcher, the portal and the marketing site. It lives
// at backoffice/universal-platform/scripts/app-marks/own-icons/<id>.svg, and
// `webIcon` on the Universal_Screens entry in marks.mjs points at it.
if (process.env.SVG_OUT) {
  writeFileSync(process.env.SVG_OUT, svg() + '\n')
  process.exit(0)
}

const browser = await chromium.launch()

/**
 * Render to PNG.
 * @param {number} size canvas edge in px
 * @param {string} art  the SVG (or any HTML)
 * @param {{ inset?: number, radius?: string, ground?: string | null, shadow?: boolean }} o
 *   inset — share of the canvas the art takes; radius — CSS corner rounding of
 *   the art; ground — the canvas colour, or null for transparent; shadow — the
 *   macOS dock drop shadow, scaled to `size` (a fixed px shadow would swamp a
 *   32px icon and vanish on a 1024 one).
 */
async function png(size, art, { inset = 1, radius = '0', ground = null, shadow = false } = {}) {
  const k = size / 1024
  const box = shadow ? `0 ${(10 * k).toFixed(2)}px ${(18 * k).toFixed(2)}px rgb(0 0 0 / .28)` : 'none'
  const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 })
  const pct = (inset * 100).toFixed(4)
  await page.setContent(`<!doctype html><style>
    html,body{margin:0;width:${size}px;height:${size}px;background:${ground ?? 'transparent'};display:grid;place-items:center}
    body>div{width:${pct}%;height:${pct}%;border-radius:${radius};overflow:hidden;box-shadow:${box}}
  </style><div>${art}</div>`)
  const buf = await page.screenshot({ omitBackground: ground === null })
  await page.close()
  return buf
}

const written = []
const skipped = []
function put(rel, data) {
  const file = path.join(root, rel)
  mkdirSync(path.dirname(file), { recursive: true })
  try {
    if (readFileSync(file).equals(Buffer.from(data))) { skipped.push(rel); return }
  } catch { /* new file */ }
  writeFileSync(file, data)
  written.push(rel)
}

if (process.env.PREVIEW) {
  mkdirSync(process.env.PREVIEW, { recursive: true })
  for (const size of [1024, 512, 256, 128, 64, 48, 32, 16]) {
    writeFileSync(
      path.join(process.env.PREVIEW, `icon-${size}.png`),
      await png(size, svg(), { radius: '22.4%' }),
    )
  }
  writeFileSync(path.join(process.env.PREVIEW, 'icon-mac-1024.png'),
    await png(1024, svg(), { inset: 824 / 1024, radius: '22.4%', shadow: true }))
  writeFileSync(path.join(process.env.PREVIEW, 'icon.svg'), svg())
  await browser.close()
  console.log(`Preview: ${process.env.PREVIEW}`)
  process.exit(0)
}

// ── Container writers ───────────────────────────────────────────────────────
// Lifted wholesale from Universal_PDF/scripts/app-icon.mjs, which took them
// from the suite generator. Same bytes in, same bytes out.
const ICO_SIZES = [16, 24, 32, 48, 64, 128, 256]
// ⚠️ Never the icp4/icp5/icp6 slots: Finder reads them as raw pixels and a PNG
// in them shows as noise (2026-09-27). Small sizes go in the retina slots.
const ICNS_TYPES = { 32: ['ic11'], 64: ['ic12'], 128: ['ic07'], 256: ['ic08', 'ic13'], 512: ['ic09', 'ic14'], 1024: ['ic10'] }

function ico(images) {
  const header = Buffer.alloc(6)
  header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(images.length, 4)
  let offset = 6 + images.length * 16
  const entries = images.map(({ size, data }) => {
    const e = Buffer.alloc(16)
    e.writeUInt8(size >= 256 ? 0 : size, 0); e.writeUInt8(size >= 256 ? 0 : size, 1)
    e.writeUInt16LE(1, 4); e.writeUInt16LE(32, 6)
    e.writeUInt32LE(data.length, 8); e.writeUInt32LE(offset, 12)
    offset += data.length
    return e
  })
  return Buffer.concat([header, ...entries, ...images.map((i) => i.data)])
}
function icns(images) {
  const chunks = []
  for (const { size, data } of images) {
    for (const type of ICNS_TYPES[size]) {
      const h = Buffer.alloc(8)
      h.write(type, 0, 'ascii'); h.writeUInt32BE(data.length + 8, 4)
      chunks.push(h, data)
    }
  }
  const body = Buffer.concat(chunks)
  const h = Buffer.alloc(8)
  h.write('icns', 0, 'ascii'); h.writeUInt32BE(body.length + 8, 4)
  return Buffer.concat([h, body])
}

// ── Desktop hosts ───────────────────────────────────────────────────────────
// Windows and Linux mask nothing, so the icon carries its own rounded corners.
put('crates/host-windows/assets/app-icon.png', await png(256, svg(), { radius: '22.4%' }))
put('crates/host-linux/assets/app-icon.png', await png(512, svg(), { radius: '22.4%' }))
put('crates/host-macos/assets/app-icon.png', await png(1024, svg(), { radius: '22.4%' }))

// The .exe icon, every Windows shortcut, and Add/Remove Programs.
put('crates/host-windows/assets/app-icon.ico', ico(
  await Promise.all(ICO_SIZES.map(async (size) => ({
    size, data: await png(size, svg(), { radius: '22.4%' }),
  }))),
))

// macOS draws dock icons on Apple's grid: an 824 rounded square in a 1024
// canvas, with room for the shadow. Full bleed and the app stands a size
// larger than everything else in the Dock.
put('crates/host-macos/assets/AppIcon.icns', icns(
  await Promise.all(Object.keys(ICNS_TYPES).map(Number).sort((a, b) => a - b).map(async (size) => ({
    size, data: await png(size, svg(), { inset: 824 / 1024, radius: '22.4%', shadow: true }),
  }))),
))

// ── iOS ─────────────────────────────────────────────────────────────────────
// ⚠️ Opaque and full bleed. iOS rounds the corners itself, and the App Store
// REJECTS an icon with an alpha channel at upload — not at build time, so a
// transparent icon gets all the way to review before anything complains.
// The filename is the one Contents.json already references; writing any other
// name is a silent no-op that leaves Xcode compiling the old art.
put('apps/ios/ScreenExtender/Assets.xcassets/AppIcon.appiconset/icon-1024.png',
  await png(1024, svg(), { ground: TEAL_DEEP }))

// ── Android ─────────────────────────────────────────────────────────────────
const RES = 'apps/android/app/src/main/res'
const DENSITIES = { 'mipmap-mdpi': 1, 'mipmap-hdpi': 1.5, 'mipmap-xhdpi': 2, 'mipmap-xxhdpi': 3, 'mipmap-xxxhdpi': 4 }
for (const [dir, scale] of Object.entries(DENSITIES)) {
  const launcher = Math.round(48 * scale)
  const adaptive = Math.round(108 * scale)
  // Pre-Android 8: nothing masks these, so they carry their own shape.
  put(`${RES}/${dir}/ic_launcher.png`, await png(launcher, svg(), { inset: 0.92, radius: '22.4%' }))
  put(`${RES}/${dir}/ic_launcher_round.png`, await png(launcher, svg(), { inset: 0.92, radius: '50%' }))
  // ⚠️ The foreground draws NO GROUND of its own. The background below is a
  // gradient, and an inset copy of a gradient runs its whole ramp inside the
  // outer one's — matching at the centre and nowhere else, which shows up as a
  // rounded rectangle outlined in slightly-wrong teal.
  put(`${RES}/${dir}/ic_launcher_foreground.png`, await png(adaptive, svg({ wide: true, back: false })))
}

const HEADER = `<!-- GENERATED FILE — do not edit by hand.
     Source: scripts/app-icon.mjs (Screens draws its own installed-app icon;
     the suite generators skip it — see ownNativeIcon in
     backoffice/universal-platform/scripts/app-marks/marks.mjs)
     Regenerate: node scripts/app-icon.mjs -->`

// ⚠️ A <shape> drawable, not the @color resource: a colour resource holds one
// value and cannot hold a ramp, and this ground is a gradient. angle 315
// matches the 0,0 → 1,1 direction the SVG's `bg` gradient runs.
put(`${RES}/drawable/ic_launcher_tile.xml`, `<?xml version="1.0" encoding="utf-8"?>
${HEADER}
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:startColor="${TEAL}" android:endColor="${TEAL_DEEP}" android:angle="315"/>
</shape>
`)
// Kept correct because the Gradle project's own references to it outlive our
// repointing — but it can only carry the ground flattened, so nothing should
// read it for artwork.
put(`${RES}/values/ic_launcher_background.xml`, `<?xml version="1.0" encoding="utf-8"?>
${HEADER}
<resources>
    <color name="ic_launcher_background">${TEAL_DEEP}</color>
</resources>
`)

await browser.close()
console.log(written.length
  ? `Wrote ${written.length} file(s)${skipped.length ? `, ${skipped.length} unchanged` : ''}:\n  ${written.join('\n  ')}`
  : `Nothing changed (${skipped.length} file(s) already current).`)
